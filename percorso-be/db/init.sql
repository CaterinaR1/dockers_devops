CREATE TABLE IF NOT EXISTS accounts (
  id SERIAL PRIMARY KEY,
  iban VARCHAR(34) NOT NULL UNIQUE,
  balance NUMERIC(15, 2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

